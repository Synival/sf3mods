[[gnu::section(".getBattleAnimationInfo")]]
int getBattleAnimationInfo(int32_t fileId, animId_e32 animId, aniInfo_t *aniInfoOut) {
    if (fileId < 0x31f || (animId & 0x0F) != 0)
        return 0;

    uint16_t curModelFileId = 0x31f;
    uint16_t curAnimFileId  = 0x2fb;

    // Maps (animId >> 4) to the aniBit. Invalid animIds will yield 0.
    static const uint8_t aniBitMap[16] = {
        0,     // 0x00 (never present)
        0,     // 0x10 (never present)
        0,     // 0x20 (never present)
        0x01,  // 0x30 (animIds are always in this unintuitive order: 0x30, 0x60, 0x40, 0x50)
        0x04,  // 0x40
        0x08,  // 0x50
        0x02,  // 0x60
        0,     // 0x70 (never present)
        0x10,  // 0x80
        0x20,  // 0x90
        0x40,  // 0xa0
        0,     // 0xb0 (never present)
        0,     // 0xc0 (never present)
        0,     // 0xd0 (never present)
        0,     // 0xe0 (never present)
        0x80   // 0xf0
    };
    uint8_t aniBit = aniBitMap[animId >> 4];
    if (aniBit == 0)
        return 0;

    const uint8_t *bytePtr = g_battleAnimationLookupData;
    while (*bytePtr != 0xff) {
        uint8_t  animFileIdAndTotalModelFileDelta = *(bytePtr++);
        uint8_t  totalFileIdDeltas                = animFileIdAndTotalModelFileDelta >> 3;
        uint16_t lastModelFileIdHere              = curModelFileId + totalFileIdDeltas;
        curAnimFileId += (animFileIdAndTotalModelFileDelta & 0x07);

        if (fileId > lastModelFileIdHere) {
            // It's not in here! Just skip ahead.
            curModelFileId += totalFileIdDeltas;
            while (1) {
                uint8_t numBitsAndModelFileIdDelta = *(bytePtr++);
                if (numBitsAndModelFileIdDelta == 0xff)
                    break;
                uint8_t numSizeBits = numBitsAndModelFileIdDelta >> 4;
                bytePtr += numSizeBits + 1;
            }
        }
        else {
            // It's in here! Find the file, if it exists.
            uint16_t curAnimFilePos = 0;
            while (1) {
                uint8_t numBitsAndModelFileIdDelta = *(bytePtr++);

                // If not found, it's guaranteed nowhere in this table; return.
                if (numBitsAndModelFileIdDelta == 0xff)
                    return 0;

                uint8_t modeFileIdDelta = numBitsAndModelFileIdDelta & 0x0f;
                curModelFileId += modeFileIdDelta;

                uint8_t aniBits = *(bytePtr++);
                if (curModelFileId == fileId) {
                    // If the requested animation bit isn't set, it doesn't exist.
                    if ((aniBits & aniBit) == 0)
                        return 0;

                    // Skip ahead to the animation.
                    for (uint16_t curBit = 1; curBit < aniBit; curBit <<= 1) {
                        if ((aniBits & curBit) == 0)
                            continue;
                        uint8_t animFileSize = *(bytePtr++);
                        curAnimFilePos += animFileSize;
                    }

                    // The current byte is at our animation.
                    aniInfoOut->modelFileId  = curModelFileId;
                    aniInfoOut->animFileId   = curAnimFileId,
                    aniInfoOut->animFilePos  = curAnimFilePos;
                    aniInfoOut->animFileSize = *(bytePtr);
                    return 1;
                }
                else {
                    uint8_t numSizeBits = numBitsAndModelFileIdDelta >> 4;
                    for (int i = 0; i < numSizeBits; i++)
                        curAnimFilePos += *(bytePtr++);
                }
            }
        }
    }

    return 0;
}

