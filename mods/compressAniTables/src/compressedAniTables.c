[[gnu::section(".loadBattleAnimation")]]
void loadBattleAnimation(polyChar_scn1_t *polyChar, animId_e32 animId) {
    int32_t fileId;

    if (polyChar == nullptr || polyChar->modelAnimRamAddr == nullptr || polyChar->currentAnimId == animId || g_animLoaded)
        return;

    fileId = getBattleModelIdFileId((int)polyChar->battleModelId);
    if (fileId == -1)
        return;

    if ((int)polyChar->animId == (int)polyChar->currentAnimId)
        unknownAnimLoadingFunc(polyChar, -1);

    aniInfo_t aniInfo;
    if (getBattleAnimationInfo(fileId, animId, &aniInfo)) {
        polyChar->currentAnimId              = (animId_e16) animId;
        g_battleAnimationLoadingFileQueueIdx = loadPartialFileToAddrWithoutCallback(
            aniInfo.animFileId, polyChar->modelAnimRamAddr, aniInfo.animFilePos * 0x800, aniInfo.animFileSize << 0xb);
        g_animLoaded                     = 1;
        g_battleAnimationLoadingPolyChar = polyChar;
    }
}

